            <LI>หลักสูตร 30 จาก 297 หลักสูตรของ มข. ไม่มี PDF หลักสูตรปัจจุบันบนดิสก์ จึงไม่มีบันทึกทักษะที่สกัดได้ — มิติ Relevance เป็นค่าว่าง</LI>
