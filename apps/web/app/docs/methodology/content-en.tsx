          <DocSubSubsection number="2.2.1" title="Attractiveness">
            <P>
              The Attractiveness dimension answers:{' '}
              <Em>
                Are students actively choosing this program over its alternatives, and does the choice
                translate into enrolment?
              </Em>{' '}
              Inputs are the TCAS rounds 1–4 recruitment funnel — sourced from{' '}
              <Code>POWERBI.ADMISSION_STAT</Code>, the registrar's campaign-grain admission feed
              (one row per recruitment track within program × round × year) — plus the
              registrar's enrolment series.
            </P>
            <Tbl>
              <THead>
                <TR>
                  <TH width="24%">Driver</TH>
                  <TH width="40%">Formula</TH>
                  <TH>Data source</TH>
                </TR>
              </THead>
              <tbody>
                <TR>
                  <TD mono>tcas_competition_ratio</TD>
                  <TD>Piecewise function of <Code>applicants / enrollSeats</Code>. ratio ≥ 10 → 100; 5 → 70; 2 → 40; 1 → 20; below 1 scales linearly to 0.</TD>
                  <TD><Code>admission_campaign_stats</Code> (POWERBI.ADMISSION_STAT — latest <Strong>complete</Strong> entry-year, summed across rounds 1–4).</TD>
                </TR>
                <TR>
                  <TD mono>tcas_fill_rate</TD>
                  <TD><Code>min(passed / enrollSeats, 0.5) ÷ 0.5 × 100</Code></TD>
                  <TD>Same as above.</TD>
                </TR>
                <TR>
                  <TD mono>tcas_registration_yield</TD>
                  <TD>yield = <Code>regReported / sendClearinghouse</Code>. ≥ 0.85 → 100; 0.5 → 50; below 0.5 scales linearly to 0.</TD>
                  <TD>Same as above.</TD>
                </TR>
                <TR>
                  <TD mono>tcas_competition_vs_peers</TD>
                  <TD><Code>(kkuRatio / peerMedianRatio) × 50</Code>, clamped. Score 50 = parity with the Thai peer median; 100 = 2× peer median.</TD>
                  <TD>KKU funnel above + <Code>tcas_admission_stats</Code> peer rows for matching subject signature, same year.</TD>
                </TR>
                <TR>
                  <TD mono>enrollment_trend_slope</TD>
                  <TD>Linear-regression slope of <Code>enrolled</Code> over the most recent 5 years (with a partial-current-year drop). 0 students/year → 50; +5/yr → 100; −5/yr → 0.</TD>
                  <TD><Code>enrollment_metrics</Code> (KKU registrar, via <Code>kku-registry</Code>).</TD>
                </TR>
                <TR>
                  <TD mono>kku_intake_policy</TD>
                  <TD>Compliance with KKU's 2026 intake-floor policy: 30 students/yr for Bachelor's, 8 for postgraduate. Bachelor breach scales linearly toward 0; postgraduate breach scales toward 30.</TD>
                  <TD><Code>enrollment_metrics</Code> + Program level.</TD>
                </TR>
              </tbody>
            </Tbl>
            <P>
              The "complete" entry-year filter is significant: in-progress recruitment cycles have null{' '}
              <Code>regReported</Code> values across all rounds (Clearinghouse registration finishes
              ~October of the cohort year), and including them would zero the registration-yield driver
              in a misleading way. The application uses the most recent <Strong>completed</Strong>{' '}
              cohort and surfaces the in-progress cycle separately as informational.
            </P>
          </DocSubSubsection>

